defmodule TransactionalSystemElixirPhoenix.Features.OrquestacionDeSagaConGenServerYPatternMatchingEnElixirPhoenixFeatureTest do
  @moduledoc """
  Binds features/phoenix_saga_actor.feature to ExUnit (generated by gherkin-ai).
  Each scenario is a test, skipped while it has pending steps. Undefined steps fail the build.
  """
  use ExUnit.Case, async: true

  alias TransactionalSystemElixirPhoenix.Domain.OrquestacionDeSagaConGenServerYPatternMatchingEnElixirPhoenixAggregate

  @feature Path.expand("../../features/phoenix_saga_actor.feature", __DIR__)
  @external_resource @feature

  # {keyword, regex, status}: switch a step to :implemented once its clause below asserts real behavior.
  @steps [
    {"Given", ~r|^que un usuario realiza una acción en Phoenix LiveView enviando `phx-submit="create_order"`$|, :pending},
    {"When", ~r|^el GenServer de la Saga recibe el comando y ejecuta `Ecto\.Multi\.new\(\)`$|, :pending},
    {"Then", ~r|^el pedido y el evento Outbox son insertados atómicamente en PostgreSQL$|, :pending},
    {"Then", ~r|^Phoenix PubSub transmite el evento `\{:order_created, order\}` al proceso de LiveView$|, :pending},
    {"Then", ~r|^la prueba `mix test` verifica la ejecución sin errores de Pattern Matching o GenServer exit$|, :pending}
  ]

  @scenarios TransactionalSystemElixirPhoenix.Gherkin.scenarios(File.read!(@feature))

  defp definition(keyword, text), do: Enum.find(@steps, fn {kw, re, _} -> kw == keyword and Regex.match?(re, text) end)

  test "every step in the feature has a definition" do
    undefined =
      for {name, steps} <- @scenarios, {kw, text} <- steps, definition(kw, text) == nil, do: "#{name}: #{kw} #{text}"

    assert undefined == [], "Undefined steps:\n" <> Enum.join(undefined, "\n")
  end

  for {name, steps} <- @scenarios do
    pending? = Enum.any?(steps, fn {kw, text} -> match?({_, _, :pending}, Enum.find(@steps, fn {k, re, _} -> k == kw and Regex.match?(re, text) end)) end)
    if pending?, do: @tag(:skip)

    test "Scenario: #{name}" do
      {:ok, _aggregate} = OrquestacionDeSagaConGenServerYPatternMatchingEnElixirPhoenixAggregate.new("scenario-aggregate")
