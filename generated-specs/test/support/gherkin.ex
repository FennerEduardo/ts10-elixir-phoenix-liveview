defmodule TransactionalSystemElixirPhoenix.Gherkin do
  @moduledoc """
  Minimal Gherkin reader for ExUnit (generated by gherkin-ai): returns scenarios with their
  steps, resolving And/But to the previous keyword. Enough to bind feature files to tests.
  """

  @spec scenarios(String.t()) :: [{String.t(), [{String.t(), String.t()}]}]
  def scenarios(source) do
    source
    |> String.split(~r/\R/)
    |> Enum.map(&String.trim/1)
    |> Enum.reduce({[], nil, "Given"}, &line/2)
    |> then(fn {acc, current, _} -> Enum.reverse(push(acc, current)) end)
  end

  defp line("Scenario:" <> name, {acc, current, _}), do: {push(acc, current), {String.trim(name), []}, "Given"}
  defp line("Scenario Outline:" <> name, {acc, current, _}), do: {push(acc, current), {String.trim(name), []}, "Given"}

  defp line(text, {acc, {name, steps}, last}) do
    case Regex.run(~r/^(Given|When|Then|And|But)\s+(.+)$/, text) do
      [_, kw, step] when kw in ["And", "But"] -> {acc, {name, steps ++ [{last, step}]}, last}
      [_, kw, step] -> {acc, {name, steps ++ [{kw, step}]}, kw}
      _ -> {acc, {name, steps}, last}
    end
  end

  defp line(_text, state), do: state

  defp push(acc, nil), do: acc
  defp push(acc, scenario), do: [scenario | acc]
end
